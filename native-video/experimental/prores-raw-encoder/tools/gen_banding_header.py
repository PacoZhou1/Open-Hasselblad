"""Fit the banding-class gain surface and write prr_banding.h.

Class pixels are x odd, y % 6 == 1 (blue sites). Ratio r = (T - b) / (mean(B[y-2], B[y+2]) - b) with b the
frame's own optical-black level (the estimator prr_pre_black uses), so the surface matches what the
encoder divides by. Tile medians on a 96 x 72 grid, evaluated bilinearly between tile centres.
Train on the flat take, report residuals on held-out takes.
"""
import json
import sys
from pathlib import Path

import numpy as np
import tifffile

P = Path(__file__).resolve().parents[1]
R = P.parents[2]
NATIVE = R / 'native-video/outputs'
FRAMES = {
    'flat_214208_c1': 'source-isolated-214208/dng-sample-readback/clip1-frame-000031-UNCALIBRATED.dng',
    'flat_214208_c2': 'source-isolated-214208/dng-sample-readback/clip2-frame-000031-UNCALIBRATED.dng',
    'wall_221635_c1': 'source-isolated-221635/dng-sample-readback/clip1-frame-000031-UNCALIBRATED.dng',
    'wall_221635_c2': 'source-isolated-221635/dng-sample-readback/clip2-frame-000031-UNCALIBRATED.dng',
    'desk_235857_c1': 'source-isolated-235857/dng-sample-readback/clip1-frame-000031-UNCALIBRATED.dng',
}
TRAIN = ['flat_214208_c1', 'flat_214208_c2']
GX, GY = 96, 72
Y0, Y1, X0, X1 = 48, 2898, 40, 3880
OB_BIAS = -3.0


def ob_black(img):
    ob = np.concatenate([img[40:2940, 2:14].ravel(), img[40:2940, 3906:3918].ravel()]).astype(np.int64)
    m = int(np.median(ob >> 4))
    sel = ob[(ob >= max(m - 32, 0) << 4) & (ob < (m + 33) << 4)]
    return float(sel.mean()) + OB_BIAS


def ratio_field(img, b):
    ys = np.arange(Y0 + 6, Y1 - 6)
    ys = ys[ys % 6 == 1]
    xs = np.arange(X0, X1)
    xs = xs[xs % 2 == 1]
    t = img[np.ix_(ys, xs)] - b
    u = img[np.ix_(ys - 2, xs)] - b
    d = img[np.ix_(ys + 2, xs)] - b
    ref = 0.5 * (u + d)
    ok = (ref > 300) & (np.abs(u - d) < 0.06 * ref) & (img[np.ix_(ys, xs)] < 60000)
    return ys, xs, np.where(ok, t / np.where(ok, ref, 1), np.nan)


def edges(ys, xs):
    return np.linspace(xs.min(), xs.max() + 1, GX + 1), np.linspace(ys.min(), ys.max() + 1, GY + 1)


def tile_medians(ys, xs, vals, xe, ye, min_count=50):
    xi = np.clip(np.searchsorted(xe, xs, side='right') - 1, 0, GX - 1)
    yi = np.clip(np.searchsorted(ye, ys, side='right') - 1, 0, GY - 1)
    grid = np.full((GY, GX), np.nan)
    for j in range(GY):
        rows = vals[yi == j]
        for i in range(GX):
            v = rows[:, xi == i]
            v = v[np.isfinite(v)]
            if v.size > min_count:
                grid[j, i] = np.median(v)
    return grid


def fill_nan(g):
    g = g.copy()
    for _ in range(8):
        m = np.isnan(g)
        if not m.any():
            break
        p = np.pad(g, 1, mode='edge')
        nb = np.stack([p[:-2, 1:-1], p[2:, 1:-1], p[1:-1, :-2], p[1:-1, 2:]])
        g[m] = np.nanmean(nb, axis=0)[m]
    return g


def surface(grid, cx, cy, xs, ys):
    gx = np.array([np.interp(xs, cx, grid[j]) for j in range(GY)])
    return np.array([np.interp(ys, cy, gx[:, i]) for i in range(len(xs))]).T


def write_header(grid, cx, cy, path):
    out = ['/* Generated by tools/gen_banding_header.py from MODE21 flat-field DNG readbacks (%s).' % ', '.join(TRAIN),
           ' * Class = blue CFA sites (x odd, y % 6 == 1). Ratio = class / same-column blue rows y+-2, both',
           ' * above the frame\'s optical-black level. corrected = signal / g(x, y), bilinear between tile centres. */',
           '#ifndef PRR_BANDING_H', '#define PRR_BANDING_H', '#define PRR_BAND_GX %d' % GX, '#define PRR_BAND_GY %d' % GY,
           'static const float prr_band_cx[PRR_BAND_GX] = {' + ', '.join('%.1ff' % v for v in cx) + '};',
           'static const float prr_band_cy[PRR_BAND_GY] = {' + ', '.join('%.1ff' % v for v in cy) + '};',
           'static const float prr_band_g[PRR_BAND_GY][PRR_BAND_GX] = {']
    out += ['    {' + ', '.join('%.6ff' % v for v in row) + '},' for row in grid]
    out += ['};', '#endif']
    path.write_text('\n'.join(out) + '\n')


def main():
    imgs = {k: tifffile.imread(NATIVE / v).astype(np.float64) for k, v in FRAMES.items()}
    blacks = {k: ob_black(v) for k, v in imgs.items()}
    fields = {k: ratio_field(imgs[k], blacks[k]) for k in FRAMES}
    ys, xs, _ = fields[TRAIN[0]]
    xe, ye = edges(ys, xs)
    cx, cy = 0.5 * (xe[:-1] + xe[1:]), 0.5 * (ye[:-1] + ye[1:])
    stacked = np.concatenate([fields[k][2] for k in TRAIN], axis=0)
    grid = fill_nan(tile_medians(np.concatenate([ys] * len(TRAIN)), xs, stacked, xe, ye))
    surf = surface(grid, cx, cy, xs, ys)
    report = {'black': blacks, 'train': TRAIN, 'grid_range': [float(grid.min()), float(grid.max())],
              'x_edges': [float(xe[0]), float(xe[-1])], 'y_edges': [float(ye[0]), float(ye[-1])], 'eval': {}}
    eval_xe, eval_ye = np.linspace(xe[0], xe[-1], 25), np.linspace(ye[0], ye[-1], 19)
    for k, (_, _, r) in fields.items():
        res = {}
        for label, v in (('uncorrected', r), ('corrected', r / surf)):
            g = tile_medians(ys, xs, v, eval_xe, eval_ye)
            fin = g[np.isfinite(g)]
            res[label] = {'tile_p5_p50_p95': [round(float(np.percentile(fin, q)), 4) for q in (5, 50, 95)],
                          'tile_max_abs_err_pct': round(float(100 * np.max(np.abs(fin - 1))), 2),
                          'pixel_median_abs_err_pct': round(float(100 * np.nanmedian(np.abs(v - 1))), 2),
                          'tiles': int(fin.size)}
        res['role'] = 'train' if k in TRAIN else 'holdout'
        report['eval'][k] = res
    write_header(grid, cx, cy, P / 'prr_banding.h')
    (P / 'tools/banding_fit.json').write_text(json.dumps(report, indent=1) + '\n')
    json.dump(report, sys.stdout, indent=1)


if __name__ == '__main__':
    main()
